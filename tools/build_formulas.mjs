/**
 * Compile the LaTeX source in `tools/formulas.source.mjs` into self-contained
 * SVG, and write `src/content/formulas.generated.ts`.
 *
 * Why build-time:
 *   - MathJax emits glyphs as <path> data, so the result has no font dependency
 *     (the previous Unicode formula failed exactly there: ⋃ existed in 2 of the
 *     300 installed faces and in none of the page's stack).
 *   - Nothing ships to the browser: no MathJax runtime, no KaTeX CSS, no 20
 *     webfont files, no network request.
 *   - Inline SVG (not <img>) keeps `ex` units tied to the page font and lets
 *     the strokes inherit `currentColor`, so the formula follows the theme.
 *
 * Run: npm run build:formulas
 */

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { mathjax } from 'mathjax-full/js/mathjax.js';
import { TeX } from 'mathjax-full/js/input/tex.js';
import { SVG } from 'mathjax-full/js/output/svg.js';
import { liteAdaptor } from 'mathjax-full/js/adaptors/liteAdaptor.js';
import { RegisterHTMLHandler } from 'mathjax-full/js/handlers/html.js';
import { AllPackages } from 'mathjax-full/js/input/tex/AllPackages.js';

import { FORMULAS } from './formulas.source.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const outFile = join(here, '..', 'src', 'content', 'formulas.generated.ts');
const sourceFile = join(here, 'formulas.source.mjs');

const adaptor = liteAdaptor();
RegisterHTMLHandler(adaptor);

const tex = new TeX({ packages: AllPackages });
// fontCache: 'none' inlines every glyph, so each SVG stands alone (no <use>
// references to a shared <defs> that may not be present on the page).
const svg = new SVG({ fontCache: 'none' });
const doc = mathjax.document('', { InputJax: tex, OutputJax: svg });

/** Compile one TeX string and return only the <svg> element. */
function compile(entry) {
  const node = doc.convert(entry.tex, { display: entry.display, em: 16, ex: 8 });
  const html = adaptor.outerHTML(node);
  const match = html.match(/<svg[\s\S]*<\/svg>/);
  if (!match) throw new Error(`MathJax produced no <svg> for: ${entry.tex}`);
  return match[0]
    // The accessible name lives on the React wrapper (role="math" + a full
    // Chinese reading), so the drawing itself is hidden from screen readers.
    // MathJax already writes focusable="false"; only the screen-reader hiding
    // needs adding, and duplicating the attribute would be invalid HTML.
    .replace('<svg ', '<svg aria-hidden="true" ')
    // Belt and braces: every path must inherit the text colour.
    .replace(/fill="(?!currentColor|none)[^"]*"/g, 'fill="currentColor"');
}

const entries = Object.entries(FORMULAS);
const compiled = entries.map(([name, entry]) => [name, { ...entry, svg: compile(entry) }]);

// A hash of the source *file*, not of the output: it lets the test detect
// "TeX was edited but the generated file was not regenerated" by reading the
// same file, without importing MathJax or trusting the generated data.
const hash = createHash('sha256').update(readFileSync(sourceFile, 'utf8')).digest('hex').slice(0, 16);

const body = compiled
  .map(
    ([name, f]) =>
      `  ${JSON.stringify(name)}: {\n` +
      `    tex: ${JSON.stringify(f.tex)},\n` +
      `    label: ${JSON.stringify(f.label)},\n` +
      `    display: ${f.display},\n` +
      `    svg: ${JSON.stringify(f.svg)},\n` +
      `  },`,
  )
  .join('\n');

const file = `/* eslint-disable */
// Generated by tools/build_formulas.mjs — do not edit by hand.
// Source: tools/formulas.source.mjs. Regenerate with: npm run build:formulas
//
// Each \`svg\` is a self-contained MathJax SVG: glyphs are paths, so it needs no
// maths font and no runtime. It inherits \`currentColor\`.

export const FORMULA_SOURCE_HASH = ${JSON.stringify(hash)};

export const FORMULAS = {
${body}
} as const;

export type FormulaName = keyof typeof FORMULAS;
`;

writeFileSync(outFile, file, 'utf8');
console.log(
  `compiled ${compiled.length} formulas -> ${outFile.replace(here, '.')} ` +
    `(${(file.length / 1024).toFixed(1)} kB, source ${hash})`,
);
