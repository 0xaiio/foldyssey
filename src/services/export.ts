/**
 * Vector / raster export.
 *
 * The SVG is generated from the same MultiPolygon the engine computed —
 * never from a cached bitmap. Holes are separate closed sub-paths rendered
 * with `fill-rule="evenodd"`, so they stay genuinely transparent.
 */

import { type MultiPolygon, exportPath } from '../geometry/polygon';

export const EXPORT_SIZE = 1000;
const PAD = 56;

export type ExportStyle = {
  paperColor: string;
  backgroundColor: string;
  title: string;
};

export function artworkPath(paper: MultiPolygon): string {
  return exportPath(paper, EXPORT_SIZE, PAD);
}

export function buildSvg(paper: MultiPolygon, style: ExportStyle): string {
  const d = artworkPath(paper);
  const title = escapeXml(style.title || 'Foldyssey papercut');
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${EXPORT_SIZE} ${EXPORT_SIZE}" width="${EXPORT_SIZE}" height="${EXPORT_SIZE}" role="img">`,
    `  <title>${title}</title>`,
    '  <desc>Generated by Foldyssey / 一刀万象 from verified fold-and-cut geometry.</desc>',
    `  <rect width="${EXPORT_SIZE}" height="${EXPORT_SIZE}" fill="${style.backgroundColor}"/>`,
    `  <path d="${d}" fill="${style.paperColor}" fill-rule="evenodd"/>`,
    '</svg>',
  ].join('\n');
}

function escapeXml(s: string): string {
  return s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

export function slugify(input: string, fallback = 'papercut'): string {
  const ascii = input
    .normalize('NFKD')
    .replace(/[^\w\s-]/g, '')
    .trim()
    .replace(/\s+/g, '-')
    .toLowerCase();
  return ascii || fallback;
}

export function timestamp(date = new Date()): string {
  const p = (n: number) => String(n).padStart(2, '0');
  return `${date.getFullYear()}${p(date.getMonth() + 1)}${p(date.getDate())}`;
}

export function fileName(title: string, ext: string): string {
  return `foldyssey-${slugify(title)}-${timestamp()}.${ext}`;
}

function triggerDownload(blob: Blob, name: string): void {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = name;
  a.rel = 'noopener';
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 4000);
}

export function downloadSvg(paper: MultiPolygon, style: ExportStyle): string {
  const svg = buildSvg(paper, style);
  const name = fileName(style.title, 'svg');
  triggerDownload(new Blob([svg], { type: 'image/svg+xml;charset=utf-8' }), name);
  return name;
}

export function downloadPng(paper: MultiPolygon, style: ExportStyle, scale = 2): string {
  const d = artworkPath(paper);
  const size = EXPORT_SIZE * scale;
  const canvas = document.createElement('canvas');
  canvas.width = size;
  canvas.height = size;
  const ctx = canvas.getContext('2d');
  if (!ctx) throw new Error('当前浏览器不支持 Canvas 导出。');
  ctx.scale(scale, scale);
  ctx.fillStyle = style.backgroundColor;
  ctx.fillRect(0, 0, EXPORT_SIZE, EXPORT_SIZE);
  const path = new Path2D(d);
  ctx.fillStyle = style.paperColor;
  ctx.fill(path, 'evenodd');
  const name = fileName(style.title, 'png');

  canvas.toBlob((blob) => {
    if (!blob) return;
    triggerDownload(blob, name);
  }, 'image/png');

  return name;
}
