export const LEVELS: PuzzleLevel[] = SEEDS.map((seed, i) => buildLevel(seed, i + 1));

export const LEVEL_MAP: Record<string, PuzzleLevel> = Object.fromEntries(
  LEVELS.map((l) => [l.id, l]),
);

export function getLevel(id: string): PuzzleLevel | undefined {
  return LEVEL_MAP[id];
}

