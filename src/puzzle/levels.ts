/**
 * Puzzle levels.
 *
 * Every target region is produced by *forward construction*: take the level's
 * canonical solution, run the real cut engine, and use the resulting paper as
 * the target. That makes "solvable" a fact of the data rather than a claim.
 *
 * Canonical solutions only use values reachable with the on-screen controls
 * (integer degrees, two-decimal offsets), so a player can reproduce them exactly.
 */

import { applyCuts, cutFromAngle, type StraightCut } from '../geometry/cut';
import type { FoldPresetId } from '../geometry/fold';
import { type MultiPolygon, multiPolygonArea } from '../geometry/polygon';
import { DEFAULT_THRESHOLDS, type ScoreThresholds } from '../geometry/score';

export type HintSet = {
  observe: string;
  operate: string;
  solution: string;
};

export type PuzzleLevel = {
  id: string;
  index: number;
  title: string;
  subtitle: string;
  brief: string;
  difficulty: 1 | 2 | 3;
  foldPreset: FoldPresetId;
  canonicalSolution: StraightCut;
  initialGuess: StraightCut;
  /** Region generated by running the canonical solution through the engine. */
  target: MultiPolygon;
  targetArea: number;
  hints: HintSet;
  knowledge: string;
  thresholds: ScoreThresholds;
  version: number;
  /** Which copy of the symmetric group the cut produces. */
  symmetryNote: string;
};

type LevelSeed = Omit<PuzzleLevel, 'target' | 'targetArea' | 'version' | 'index'>;

function buildLevel(seed: LevelSeed, index: number): PuzzleLevel {
  const outcome = applyCuts(seed.foldPreset, [seed.canonicalSolution]);
  const area = multiPolygonArea(outcome.paper);
  if (!outcome.ok || area <= 1e-6) {
    throw new Error(`Level "${seed.id}" has a degenerate target region.`);
  }
  return { ...seed, index, target: outcome.paper, targetArea: area, version: 1 };
}

